// Prebuild step: embed packages/shared/skills/*.md into a generated TS
// module so both surfaces can serve skill content without shipping (or
// resolving) loose .md files at runtime. The CLI's `slates install-skills`
// writes these to Claude Code and Codex skill directories; the MCP-only path reads
// them via the slates_get_prompting_guide op.
//
// Output: packages/shared/src/skills/content.ts (gitignored, regenerated
// on every build/typecheck). Each file's content is JSON.stringify'd so
// backticks / ${ / backslashes in the markdown can't break the module.

import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadTypeScriptModule } from '../../../scripts/load-typescript.mjs'

const { parseSkillMetadata } = loadTypeScriptModule(new URL('../src/skills/metadata.ts', import.meta.url))

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = join(here, '..')
const skillsDir = join(pkgRoot, 'skills')
const outDir = join(pkgRoot, 'src', 'skills')
const outFile = join(outDir, 'content.ts')

const files = readdirSync(skillsDir)
  .filter((f) => f.endsWith('.md'))
  .sort()

if (files.length === 0) {
  console.error(`[embed-skills] no .md files found in ${skillsDir}`)
  process.exit(1)
}

let out = '// GENERATED — do not edit. Source: packages/shared/skills/*.md\n'
out += '// Regenerated by scripts/embed-skills.mjs on every build.\n\n'
out += 'export const SKILLS: Record<string, string> = {\n'
for (const f of files) {
  const name = basename(f, '.md')
  const content = readFileSync(join(skillsDir, f), 'utf8')
  parseSkillMetadata(content, name)
  out += `  ${JSON.stringify(name)}: ${JSON.stringify(content)},\n`
}
out += '}\n'

mkdirSync(outDir, { recursive: true })
writeFileSync(outFile, out)
console.log(`[embed-skills] embedded ${files.length} skill(s) into src/skills/content.ts`)

// HyperFrames' own skills, copied unmodified into skills/hyperframes/<name>/ (its NOTICE): every
// markdown file, keyed `<name>` for a skill's SKILL.md and `<name>/<path>` for the rest, plus
// SLATES-MAPPING.md. Their own frontmatter is validated by the same parser; a folder that fails it is
// handled here, in the index, never by editing the copied file.
const hfDir = join(skillsDir, 'hyperframes')
const hfOut = join(outDir, 'hyperframes-content.ts')
const mdUnder = (dir, prefix = '') =>
  readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const rel = prefix ? `${prefix}/${entry.name}` : entry.name
      if (entry.isDirectory()) return mdUnder(join(dir, entry.name), rel)
      return entry.name.endsWith('.md') ? [rel] : []
    })
const hfSkills = readdirSync(hfDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()
if (hfSkills.length === 0) {
  console.error(`[embed-skills] no HyperFrames skill folders found in ${hfDir}`)
  process.exit(1)
}
let hf = '// GENERATED — do not edit. Source: packages/shared/skills/hyperframes/ (HyperFrames, Apache-2.0, see its NOTICE)\n'
hf += '// Regenerated by scripts/embed-skills.mjs on every build. Loaded on first use by src/skills/hyperframes.ts.\n\n'
hf += `export const HYPERFRAMES_SKILL_NAMES: readonly string[] = ${JSON.stringify(hfSkills)}\n\n`
hf += 'export const HYPERFRAMES_FILES: Record<string, string> = {\n'
const slatesNames = new Set(files.map((f) => basename(f, '.md')))
let hfFiles = 0
for (const name of hfSkills) {
  if (slatesNames.has(name)) {
    console.error(`[embed-skills] HyperFrames skill ${name} has the name of a Slates skill`)
    process.exit(1)
  }
  if (!existsSync(join(hfDir, name, 'SKILL.md'))) {
    console.error(`[embed-skills] HyperFrames folder ${name} has no SKILL.md`)
    process.exit(1)
  }
  for (const rel of mdUnder(join(hfDir, name))) {
    const content = readFileSync(join(hfDir, name, rel), 'utf8')
    if (rel === 'SKILL.md') parseSkillMetadata(content, name)
    hf += `  ${JSON.stringify(rel === 'SKILL.md' ? name : `${name}/${rel}`)}: ${JSON.stringify(content)},\n`
    hfFiles++
  }
}
hf += `  ${JSON.stringify('SLATES-MAPPING.md')}: ${JSON.stringify(readFileSync(join(hfDir, 'SLATES-MAPPING.md'), 'utf8'))},\n`
hf += '}\n'
writeFileSync(hfOut, hf)
console.log(`[embed-skills] embedded ${hfSkills.length} HyperFrames skill(s), ${hfFiles} markdown file(s), into src/skills/hyperframes-content.ts`)
